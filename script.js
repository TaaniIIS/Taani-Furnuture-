const productGrid = document.getElementById('productGrid');
const langButtons = document.querySelectorAll('.lang-btn');
const form = document.getElementById('quoteForm');
const formStatus = document.getElementById('formStatus');
const slideButtons = document.querySelectorAll('.slide-btn');
const slideDots = document.querySelectorAll('.slide-dot');
const slides = document.querySelectorAll('.slide');
let activeSlideIndex = 0;
let slideIntervalId = null;

function showSlide(index) {
  activeSlideIndex = (index + slides.length) % slides.length;

  slides.forEach((slide, slideIndex) => {
    slide.classList.toggle('is-active', slideIndex === activeSlideIndex);
  });

  slideDots.forEach((dot, dotIndex) => {
    dot.classList.toggle('is-active', dotIndex === activeSlideIndex);
  });
}

function startSlideRotation() {
  clearInterval(slideIntervalId);
  slideIntervalId = setInterval(() => {
    showSlide(activeSlideIndex + 1);
  }, 5000);
}

slideButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const isNext = button.classList.contains('next');
    showSlide(activeSlideIndex + (isNext ? 1 : -1));
    startSlideRotation();
  });
});

slideDots.forEach((dot) => {
  dot.addEventListener('click', () => {
    showSlide(Number(dot.dataset.slide));
    startSlideRotation();
  });
});

function renderProducts() {
  productGrid.innerHTML = products
    .map(
      (product) => `
        <article class="product-card">
          <div class="product-image">
            <img src="${product.image}" alt="${product.name}" />
            <span class="demo-badge">Demo</span>
          </div>
          <div class="product-body">
            <div class="product-head">
              <h3>${product.name}</h3>
              <span class="product-category">${product.category}</span>
            </div>
            <p>${product.description}</p>
            <div class="product-footer">
              <span class="price ${product.price ? '' : 'contact-only'}">
                ${product.price ? `$${product.price}` : 'Contact for Price'}
              </span>
              <a class="link-btn" href="#contact">Ask Now</a>
            </div>
          </div>
        </article>
      `,
    )
    .join('');
}

function applyLanguage(lang) {
  const keys = translations[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (keys[key]) {
      element.textContent = keys[key];
    }
  });

  langButtons.forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle('active', isActive);
  });

  const statusText = lang === 'so' ? 'Fadlan buuxi foomka...' : 'Please complete the form...';
  formStatus.textContent = formStatus.dataset.default || statusText;
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

form.addEventListener('submit', (event) => {
  event.preventDefault();
  const currentLang = document.documentElement.lang || 'en';
  const successMessage =
    currentLang === 'so'
      ? 'Fariintaada waa la diiwaangeliyey. Taani Furniture waxay kula soo xiriiri doontaa dhawaan.'
      : 'Your request has been noted. Taani Furniture will contact you soon.';

  formStatus.textContent = successMessage;
  form.reset();
});

renderProducts();
applyLanguage('en');

if (slides.length) {
  startSlideRotation();
}
